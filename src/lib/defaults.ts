/**
 * Returns a copy of the default 64-byte buffer for the given model ID.
 * If a model does not have an explicit capture in MODEL_DEFAULTS, synthesizes
 * a compliant 64-byte buffer with valid metadata bytes and clamped knob values.
 */
export function getModelDefault(id: number): Uint8Array | null {
  const data = MODEL_DEFAULTS[id];
  if (data) return new Uint8Array(data);

  const model = findEffectModel(id) ?? findAmpModel(id);
  if (!model) return null;

  const buffer = new Uint8Array(64);
  buffer[0] = 0x1c;
  buffer[1] = 0x03;
  buffer[2] = model.type;
  buffer[6] = 0x01;
  buffer[7] = 0x01;
  buffer[16] = (model.id >> 8) & 0xff;
  buffer[17] = model.id & 0xff;
  if (model.type !== DspType.AMP) {
    const [m0, m1, m2] = getEffectWireMeta(model.id, model.type);
    buffer[19] = m0;
    buffer[20] = m1;
    buffer[21] = m2;
  }
  model.knobs.forEach((knobName, index) => {
    if (knobName && 32 + index < 64) {
      buffer[32 + index] =
        model.type !== DspType.AMP ? clampEffectKnob(model.id, index, model.knobSpecs?.[index] ? 0 : 0x80) : 0x80;
    }
  });
  return buffer;
}
